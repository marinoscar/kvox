import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { APP_NAME, CLI_NAME } from '@app/shared';
import { createCli, envPrefix } from '@marinoscar/platform-cli';
import { resetCliForTests } from '@marinoscar/platform-cli/testing';
import { beforeAll, describe, expect, it } from 'vitest';

import { APP_CLI_OPTIONS } from './app.js';

// =============================================================================
// The worker container's environment surface  (issue #278, epic #254; #482)
// =============================================================================
//
// A Dockerfile and a compose file cannot call TypeScript, so the worker's
// environment-variable names are written out a second time in both. Nothing
// about a stale literal fails at build time or at run time; it just quietly
// stops working. So the duplication is guarded in BOTH DIRECTIONS:
//
//   (a) every variable the worker engine reads appears in both files, which
//       catches an engine rename the files did not follow (the container would
//       set variables nothing reads);
//   (b) every prefixed token in those files is a variable the engine reads,
//       which catches a variable hand-added to compose that no code reads.
//
// Before the CLI moved onto the platform, "the variables the worker reads" was
// this package's own `WORKER_ENV` map. It is now the platform's `workerEnv()`,
// which is internal to the package (no public entry point), so the list is read
// from its built file by URL (PLATFORM-ADOPTION-SHIM(#482): removed when the
// package exports `workerEnvNames`): a test-only reach into an internal, taken on
// purpose, because the alternative is a third hand-typed copy of the names. If
// the package moves the file, this test fails loudly rather than going green.
// =============================================================================

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(HERE, '..', '..', '..');

const GUARDED_FILES = [
  join(REPO_ROOT, 'apps', 'cli', 'Dockerfile'),
  join(REPO_ROOT, 'infra', 'compose', 'worker.compose.yml'),
] as const;

const README = join(REPO_ROOT, 'apps', 'cli', 'README.md');

let workerEnvNames: string[];

beforeAll(async () => {
  resetCliForTests();
  createCli(APP_CLI_OPTIONS);

  const packageJson = createRequire(import.meta.url).resolve('@marinoscar/platform-cli/package.json');
  const moduleUrl = pathToFileURL(join(dirname(packageJson), 'dist', 'engine', 'node', 'worker-env.js')).href;
  const engine = (await import(moduleUrl)) as { workerEnvNames(): string[] };

  workerEnvNames = engine.workerEnvNames();
});

describe('the worker environment variables the engine reads', () => {
  it('are prefixed with the CLI identity and include the server URL and token', () => {
    expect(workerEnvNames.length).toBeGreaterThanOrEqual(14);
    for (const name of workerEnvNames) expect(name.startsWith(envPrefix()), name).toBe(true);
    expect(workerEnvNames).toContain(`${envPrefix()}SERVER_URL`);
    expect(workerEnvNames).toContain(`${envPrefix()}TOKEN`);
  });
});

describe('the worker container guard', () => {
  const contents = GUARDED_FILES.map((path) => [path, readFileSync(path, 'utf8')] as const);

  it('reads both guarded files (the guard is not vacuously green)', () => {
    for (const [path, body] of contents) expect(body.length, path).toBeGreaterThan(200);
  });

  it.each(contents.map(([path]) => path))('direction (a): %s declares every variable the worker reads', (path) => {
    const body = readFileSync(path, 'utf8');
    // A trailing boundary, not a bare `includes`: one name can be a PREFIX of a
    // renamed one, which a substring check would pass over.
    const missing = workerEnvNames.filter((name) => !new RegExp(`${name}(?![A-Z0-9_])`).test(body));

    expect(missing, `${path} is missing ${missing.join(', ')}`).toEqual([]);
  });

  it.each(contents.map(([path]) => path))('direction (b): every prefixed token in %s is read by the worker', (path) => {
    const body = readFileSync(path, 'utf8');
    const declared = new Set(workerEnvNames);
    const strays = [...new Set(body.match(new RegExp(`${envPrefix()}[A-Z0-9_]+`, 'g')) ?? [])].filter(
      (name) => !declared.has(name),
    );

    expect(strays, `${path} names ${strays.join(', ')}, which no code reads`).toEqual([]);
  });

  it('neither file contains a product, app or repository name outside the variable prefix', () => {
    // Branding somebody typed in by hand (a worker service key, a hardcoded
    // image name) is what (a) and (b) cannot see. Comment lines are skipped:
    // `worker.compose.yml` is generated by `platform-infra sync` with the CLI
    // name rendered into its prose (`... from \`<cli> node enroll\``, #483), which is
    // the identity working as designed, not branding typed in by hand.
    const prefixed = new RegExp(`${envPrefix()}[A-Z0-9_]+`, 'g');

    for (const [path, body] of contents) {
      const code = body
        .split('\n')
        .filter((line) => !line.trimStart().startsWith('#'))
        .join('\n');
      const lower = code.replace(prefixed, '').toLowerCase();
      expect(lower, path).not.toContain(APP_NAME.toLowerCase());
      expect(lower, path).not.toContain(CLI_NAME.toLowerCase());
    }
  });

  it("documents every variable in apps/cli's README table", () => {
    const readme = readFileSync(README, 'utf8');
    const missing = workerEnvNames.filter((name) => !readme.includes(`\`${name}\``));

    expect(missing, `apps/cli/README.md does not document ${missing.join(', ')}`).toEqual([]);
  });
});
