/**
 * Settings → Getting started (`/settings/getting-started`).
 *
 * The platform's `GettingStartedPage` (issue #481, epic #478) with this app's explanation of
 * AI keys in its `BeforeContent` slot. It sits ABOVE the checklist because it has to be readable
 * before the user needs it, not at the moment the "Add your AI provider key" step would have
 * told them anyway: a user who meets that step with no context reads it as a product demanding a
 * credential it has not earned.
 *
 * The three facts are separately surprising and none implies the others, so all three are
 * stated (`BYOK_FACTS`, asserted by name in the spec). The welcome dialog states the same three
 * more briefly (`BYOK_DIALOG_FACTS`); they are written for different moments (the sentence you
 * read while deciding whether to keep the tab open, and the paragraph you read while about to
 * paste a key) and are deliberately not one constant.
 *
 * It refreshes the checklist when it mounts: the shell's provider reads once and does not poll,
 * and a user returning from "New transcript" must see that step done.
 *
 * Ungated like every `/settings/*` sibling: the route needs only `user_settings:read`, which every
 * role holds, so a Viewer (this application's default role) is not shut out of the one page that
 * explains why AI features will ask them for a key.
 */

import { useEffect } from 'react';
import Link from '@mui/material/Link';
import Paper from '@mui/material/Paper';
import Stack from '@mui/material/Stack';
import Typography from '@mui/material/Typography';
import { Link as RouterLink } from 'react-router-dom';
import { useOnboarding } from '@marinoscar/platform-web/onboarding/headless';
import { GettingStartedPage, type GettingStartedPageSlots } from '@marinoscar/platform-web/onboarding/ui';

/** Where the AI key is added (the platform's per-user AI keys page). */
export const AI_SETTINGS_PATH = '/settings/ai';

export const BYOK_FACTS = [
  'The key is yours. You create it in your provider’s own console and paste it here — nobody else can see it, and you can remove it at any time.',
  'The usage is billed to your account. Every note you generate is a request made with your key, against whatever plan or credit you hold with that provider.',
  'This deployment stores no key of its own. There is no shared key to fall back on: without yours, the AI features stay switched off for you and nothing is generated.',
] as const;

function ByokNote() {
  return (
    <Paper component="section" variant="outlined" sx={{ p: { xs: 2, sm: 3 }, mb: 3 }}>
      <Typography variant="h6" component="h2">
        About AI features and your own key
      </Typography>
      <Typography variant="body2" color="text.secondary" sx={{ mt: 0.5 }}>
        Notes are generated by an AI provider, and this application asks you to bring your own
        account for that. Three things follow from it:
      </Typography>
      <Stack component="ul" spacing={1} sx={{ mt: 1.5, mb: 0, pl: 3 }}>
        {BYOK_FACTS.map((fact) => (
          <Typography component="li" variant="body2" key={fact}>
            {fact}
          </Typography>
        ))}
      </Stack>
      <Typography variant="body2" sx={{ mt: 2 }}>
        <Link component={RouterLink} to={AI_SETTINGS_PATH}>
          Connect your AI provider key
        </Link>{' '}
        whenever you are ready. Nothing else on this page depends on it.
      </Typography>
    </Paper>
  );
}

const SLOTS: GettingStartedPageSlots = { BeforeContent: ByokNote };

export default function GettingStartedRoute() {
  const { refresh } = useOnboarding();

  useEffect(() => {
    void refresh();
  }, [refresh]);

  return <GettingStartedPage slots={SLOTS} />;
}
