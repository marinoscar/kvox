/**
 * First line of every installed fragment copy.
 *
 * @stability experimental
 */
export const FRAGMENT_GENERATED_LINE = '// GENERATED by kvox-db sync — do not edit';

/**
 * A refusal: the plan cannot be made without breaking a rule (a host model is
 * missing, an installed migration differs from the package, a lock entry
 * disagrees). The message says what and how to fix it.
 *
 * @stability experimental
 */
export class KvoxSyncError extends Error {
  /** @param message - Why `kvox-db sync` refused. */
  constructor(message: string) {
    super(message);
    this.name = 'KvoxSyncError';
  }
}

/**
 * The directory naming policy for migrations installed by `sync`.
 *
 * `original` keeps the package id as the directory name (an app that already ran
 * the migrations under that name, such as the web app). `after-host` names it
 * `<ts>_kvox_<slug>` with a timestamp after everything already in
 * `prisma/migrations`, so a fresh host's own tables exist first.
 *
 * @stability experimental
 */
export type KvoxNamePolicy = 'original' | 'after-host';

/**
 * Options of {@link planKvoxSync}.
 *
 * @stability experimental
 */
export interface KvoxSyncOptions {
  /** The host app folder: the one that holds `prisma/`. */
  root: string;
  /** The package's fragment folder to install from; defaults to the package's `schema/`. */
  fragmentsDir?: string;
  /** The package's migrations folder to install from; defaults to the package's `migrations/`. */
  migrationsDir?: string;
  /** The naming policy; see {@link KvoxNamePolicy}. Defaults per the rule in the README ("Upgrade notes"). */
  names?: KvoxNamePolicy;
  /** Plan only: {@link applyKvoxSync} then writes nothing. */
  dryRun?: boolean;
  /** The package folder that holds the inventories and `package.json`; defaults to the installed package. */
  packageDir?: string;
  /**
   * The platform package's `schema` folder, searched (with the host's own schema) for the host models;
   * `null` searches the host only. Defaults to the one `@marinoscar/platform-db` resolves to from the host.
   */
  platformSchemaDir?: string | null;
}

/**
 * A fragment copy `sync` writes.
 *
 * @stability experimental
 */
export interface PlannedFragment {
  /** Absolute path of the installed copy under `prisma/fragments`. */
  path: string;
  /** The full file contents: header plus the package bytes. */
  contents: string;
  /** What `sync` does with it. */
  action: 'create' | 'update' | 'unchanged';
}

/**
 * A migration `sync` installs or adopts.
 *
 * @stability experimental
 */
export interface PlannedMigration {
  /** The package migration id. */
  id: string;
  /** The directory it is (or will be) installed as. */
  installedDir: string;
  /** Absolute path of the package `migration.sql`. */
  sourceFile: string;
  /** SHA-256 of its bytes. */
  sha256: string;
  /** `copy`: written now. `adopt`: already there under its original name, byte-identical, only recorded in the lock. */
  action: 'copy' | 'adopt';
}

/**
 * The `platform.lock` update `sync` plans.
 *
 * @stability experimental
 */
export interface PlannedPlatformLock {
  /** Absolute path of `prisma/platform.lock`. */
  path: string;
  /** The text to write. */
  text: string;
  /** Whether it differs from what is on disk. */
  changed: boolean;
  /** Names of the raw-SQL indexes added to `rawSqlIndexes`. */
  addedIndexes: string[];
  /** Directories added to `appMigrations`. */
  addedDirs: string[];
}

/**
 * What {@link applyKvoxSync} will write.
 *
 * @stability experimental
 */
export interface KvoxSyncPlan {
  /** The host app folder. */
  root: string;
  /** Absolute path of the host's `prisma` folder. */
  prismaDir: string;
  /** The naming policy in force. */
  names: KvoxNamePolicy;
  /** Whether {@link applyKvoxSync} must write nothing. */
  dryRun: boolean;
  /** Fragment copies, one per package fragment. */
  fragments: PlannedFragment[];
  /** Installed fragment copies with no package source; deleted. */
  staleFragments: string[];
  /** Migrations to install or adopt (those already in the lock are not listed). */
  installs: PlannedMigration[];
  /** The lock to write, and its text. */
  kvoxLock: KvoxLock;
  /** The text of the `kvox.lock` to write. */
  kvoxLockText: string;
  /** Whether `kvox.lock` changes. */
  kvoxLockChanged: boolean;
  /** The `platform.lock` update, or `undefined` when the host has none. */
  platformLock?: PlannedPlatformLock;
  /** Human-readable lines describing the plan. */
  messages: string[];
}

/**
 * Renders an installed fragment copy: the two header lines, a blank line, then
 * the package file's bytes unchanged. The header carries no version so that a
 * version bump never makes the copies stale.
 *
 * @param fileName - The package file name, for example `kvox.graph.prisma`.
 * @param packageBytes - The package file's contents.
 * @returns The text to write under `prisma/fragments`.
 * @stability experimental
 */
export function renderFragmentCopy(fileName: string, packageBytes: string): string {
  return `${FRAGMENT_GENERATED_LINE}\n// source: @marinoscar/kvox-db:schema/${fileName}\n\n${packageBytes}`;
}

/** Lists the directory names under a folder; a missing folder is empty. */
function listDirs(folder: string): string[] {
  if (!existsSync(folder)) return [];
  return readdirSync(folder, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}

const TIMESTAMP = /^(\d{14})_/;

function parseTimestamp(value: string): number {
  const y = Number(value.slice(0, 4));
  const mo = Number(value.slice(4, 6));
  const d = Number(value.slice(6, 8));
  const h = Number(value.slice(8, 10));
  const mi = Number(value.slice(10, 12));
  const s = Number(value.slice(12, 14));
  return Date.UTC(y, mo - 1, d, h, mi, s);
}

function formatTimestamp(ms: number): string {
  const date = new Date(ms);
  const pad = (n: number, width = 2) => String(n).padStart(width, '0');
  return (
    pad(date.getUTCFullYear(), 4) +
    pad(date.getUTCMonth() + 1) +
    pad(date.getUTCDate()) +
    pad(date.getUTCHours()) +
    pad(date.getUTCMinutes()) +
    pad(date.getUTCSeconds())
  );
}

/** The timestamp used when a host has no migration directory at all. */
const EMPTY_HOST_TIMESTAMP = '20240101000000';

/**
 * The directory names `after-host` gives to `ids`, in order: one second after
 * the newest timestamped directory in `existingDirs`, then one second apart.
 *
 * @param ids - Package migration ids, in run order.
 * @param existingDirs - Directory names already under the host's `prisma/migrations`.
 * @returns One directory name per id, `<ts>_kvox_<slug>`.
 * @stability experimental
 */
export function afterHostNames(ids: readonly string[], existingDirs: readonly string[]): string[] {
  let newest = EMPTY_HOST_TIMESTAMP;
  for (const dir of existingDirs) {
    const match = TIMESTAMP.exec(dir);
    if (match && match[1]! > newest) newest = match[1]!;
  }
  let ms = parseTimestamp(newest);
  return ids.map((id) => {
    ms += 1000;
    return `${formatTimestamp(ms)}_kvox_${id.slice(15)}`;
  });
}

/** Model names a text declares with `model Name {` (not `extend model`). */
function declaredModels(text: string): string[] {
  return [...text.matchAll(/^model\s+([A-Za-z_]\w*)\s*\{/gm)].map((match) => match[1]!);
}

function readPrismaFiles(folder: string, skip?: (name: string) => boolean): string[] {
  if (!existsSync(folder)) return [];
  return readdirSync(folder)
    .filter((name) => name.endsWith('.prisma') && !(skip?.(name) ?? false))
    .map((name) => readFileSync(join(folder, name), 'utf8'));
}

/**
 * Finds the host models the domain needs and that the host does not declare.
 * Looks in the composed `prisma/schema`, in the host's own fragments (not the
 * `kvox.*` copies) and, when it resolves from the host, in the platform
 * package's schema folder.
 *
 * @param prismaDir - The host's `prisma` folder.
 * @param platformSchemaDir - The platform package's `schema` folder; `null` skips it; omitted resolves it from the host.
 * @returns The missing model names (`User`, `StorageObject`, `Job`); empty when all are there.
 * @stability experimental
 */
export function findMissingHostModels(prismaDir: string, platformSchemaDir?: string | null): string[] {
  const texts = [
    ...readPrismaFiles(join(prismaDir, 'schema')),
    ...readPrismaFiles(join(prismaDir, 'fragments'), (name) => name.startsWith('kvox.')),
  ];
  if (platformSchemaDir !== null) {
    try {
      const folder =
        platformSchemaDir ??
        join(dirname(createRequire(join(dirname(prismaDir), 'noop.js')).resolve('@marinoscar/platform-db/package.json')), 'schema');
      texts.push(...readPrismaFiles(folder));
    } catch {
      // The platform package is not resolvable from the host: the composed schema must carry the models.
    }
  }
  const declared = new Set(texts.flatMap(declaredModels));
  return KVOX_HOST_MODELS.filter((model) => !declared.has(model));
}

function chooseNames(
  requested: KvoxNamePolicy | undefined,
  lock: KvoxLock | undefined,
  manifest: KvoxManifest,
  dirs: readonly string[],
): KvoxNamePolicy {
  if (requested !== undefined) return requested;
  if (lock !== undefined && lock.migrations.length > 0) {
    const first = lock.migrations[0]!;
    return first.installedDir === first.originId.slice('kvox:'.length) ? 'original' : 'after-host';
  }
  const present = new Set(dirs);
  return manifest.migrations.some((entry) => present.has(entry.id)) ? 'original' : 'after-host';
}

/**
 * Plans an install of the domain fragments and migrations into a host app:
 * reads the package, the host's `prisma` folder, `kvox.lock` and
 * `platform.lock`, decides what to write, and writes nothing.
 *
 * @param opts - See {@link KvoxSyncOptions}.
 * @returns The plan; pass it to {@link applyKvoxSync}.
 * @throws KvoxSyncError when a rule is broken (a host model is missing, the package or an installed migration was edited, a lock entry disagrees).
 * @throws KvoxLockError when a lock, the manifest or an inventory is malformed, or `platform.lock` lists an index with another definition.
 * @stability experimental
 */
export function planKvoxSync(opts: KvoxSyncOptions): KvoxSyncPlan {
  const root = resolve(opts.root);
  const prismaDir = join(root, 'prisma');
  const packageDir = resolve(opts.packageDir ?? kvoxDbPackageRoot());
  const schemaDir = resolve(opts.fragmentsDir ?? join(packageDir, 'schema'));
  const migrationsSource = resolve(opts.migrationsDir ?? join(packageDir, 'migrations'));
  const hostMigrations = join(prismaDir, 'migrations');
  const fragmentsTarget = join(prismaDir, 'fragments');
  const lockFile = join(prismaDir, KVOX_LOCK_FILE);

  const manifest = readManifest(migrationsSource);
  const inventories = readInventories(packageDir);
  const version = kvoxDbVersion(packageDir);
  const messages: string[] = [];

  const missing = findMissingHostModels(prismaDir, opts.platformSchemaDir);
  if (missing.length > 0) {
    throw new KvoxSyncError(
      `the host schema does not declare model ${missing.join(', model ')}; the domain migrations reference ` +
        `${KVOX_HOST_TABLES.join(', ')}. Install and compose the platform schema first (platform db sync, platform db compose)`,
    );
  }

  // The package must still match its own manifest: never install bytes the manifest does not vouch for.
  const packageBytes = new Map<string, Buffer>();
  for (const entry of manifest.migrations) {
    const file = join(migrationsSource, entry.id, 'migration.sql');
    if (!existsSync(file)) throw new KvoxSyncError(`the package migration ${entry.id} has no migration.sql at ${file}`);
    const bytes = readFileSync(file);
    if (sha256Hex(bytes) !== entry.sha256) {
      throw new KvoxSyncError(`the package migration ${entry.id} differs from migrations/manifest.json (sha256 mismatch); the package is corrupt or was edited`);
    }
    packageBytes.set(entry.id, bytes);
  }

  const lock = readKvoxLock(lockFile);
  const dirs = listDirs(hostMigrations);
  const names = chooseNames(opts.names, lock, manifest, dirs);
  const lockedById = new Map((lock?.migrations ?? []).map((entry) => [entry.originId, entry]));

  const entries: KvoxLockEntry[] = [];
  const installs: PlannedMigration[] = [];
  const pending: ManifestEntry[] = [];
  for (const entry of manifest.migrations) {
    const originId = `kvox:${entry.id}`;
    const locked = lockedById.get(originId);
    if (locked !== undefined) {
      if (locked.sha256 !== entry.sha256) {
        throw new KvoxSyncError(
          `${originId} is installed as ${locked.installedDir} with sha256 ${locked.sha256.slice(0, 12)} but the package now says ${entry.sha256.slice(0, 12)}; ` +
            'an installed migration is never edited, so a change must be a new migration',
        );
      }
      const installedFile = join(hostMigrations, locked.installedDir, 'migration.sql');
      if (!existsSync(installedFile)) {
        throw new KvoxSyncError(`${originId}: kvox.lock says it is installed as ${locked.installedDir} but ${installedFile} does not exist; restore it from version control, never re-install a migration that may already be applied`);
      }
      entries.push(locked);
    } else if (dirs.includes(entry.id)) {
      const installedFile = join(hostMigrations, entry.id, 'migration.sql');
      if (!existsSync(installedFile) || sha256Hex(readFileSync(installedFile)) !== entry.sha256) {
        throw new KvoxSyncError(`prisma/migrations/${entry.id} exists but is not byte-identical to the package migration; an installed migration is never edited or renamed`);
      }
      entries.push({ originId, installedDir: entry.id, sha256: entry.sha256 });
      installs.push({ id: entry.id, installedDir: entry.id, sourceFile: join(migrationsSource, entry.id, 'migration.sql'), sha256: entry.sha256, action: 'adopt' });
    } else {
      pending.push(entry);
    }
  }
  if (pending.length > 0) {
    const targetNames =
      names === 'original' ? pending.map((entry) => entry.id) : afterHostNames(pending.map((entry) => entry.id), dirs);
    pending.forEach((entry, index) => {
      const installedDir = targetNames[index]!;
      if (dirs.includes(installedDir)) {
        throw new KvoxSyncError(`prisma/migrations/${installedDir} already exists and is not recorded in kvox.lock; move it away or choose another --names policy`);
      }
      entries.push({ originId: `kvox:${entry.id}`, installedDir, sha256: entry.sha256 });
      installs.push({ id: entry.id, installedDir, sourceFile: join(migrationsSource, entry.id, 'migration.sql'), sha256: entry.sha256, action: 'copy' });
    });
    if (names === 'original') {
      const newest = dirs.filter((dir) => TIMESTAMP.test(dir)).pop();
      const oldest = pending[0]!.id;
      if (newest !== undefined && oldest < newest) {
        messages.push(`note: ${oldest} sorts before the newest host migration ${newest}; on a fresh database it would run before it. Use --names after-host on a host without kvox history`);
      }
    }
  }
  // Keep package order; entries the package no longer lists (it never removes one) stay recorded.
  const order = new Map(manifest.migrations.map((entry, index) => [`kvox:${entry.id}`, index]));
  const retained = (lock?.migrations ?? []).filter((entry) => !order.has(entry.originId));
  entries.sort((a, b) => (order.get(a.originId) ?? 0) - (order.get(b.originId) ?? 0));
  const migrations = [...entries, ...retained];

  const anyChange = installs.length > 0 || lock === undefined;
  const nextLock: KvoxLock = {
    ...(lock ?? emptyKvoxLock(version)),
    kvoxDbVersion: anyChange ? version : lock!.kvoxDbVersion,
    migrations,
  };
  const kvoxLockText = serializeKvoxLock(nextLock);
  const kvoxLockChanged = !existsSync(lockFile) || readFileSync(lockFile, 'utf8') !== kvoxLockText;

  const fragments: PlannedFragment[] = [];
  const packageFragments = listPackageFragments(schemaDir);
  for (const name of packageFragments) {
    const path = join(fragmentsTarget, name);
    const contents = renderFragmentCopy(name, readFileSync(join(schemaDir, name), 'utf8'));
    const action = !existsSync(path) ? 'create' : readFileSync(path, 'utf8') === contents ? 'unchanged' : 'update';
    fragments.push({ path, contents, action });
  }
  const staleFragments = existsSync(fragmentsTarget)
    ? readdirSync(fragmentsTarget)
        .filter((name) => /^kvox\..*\.prisma$/.test(name) && !packageFragments.includes(name))
        .map((name) => join(fragmentsTarget, name))
    : [];

  let platformLock: PlannedPlatformLock | undefined;
  const platformLockPath = join(prismaDir, 'platform.lock');
  const platformDocument = readPlatformLock(platformLockPath);
  if (platformDocument !== undefined) {
    const merge = mergePlatformLock(
      platformDocument,
      inventories.rawSqlIndexes.map(({ name, definition }) => ({ name, definition })),
      migrations.map((entry) => entry.installedDir),
    );
    const text = serializeJson(merge.document);
    platformLock = { path: platformLockPath, text, changed: readFileSync(platformLockPath, 'utf8') !== text, addedIndexes: merge.addedIndexes, addedDirs: merge.addedDirs };
  } else {
    messages.push('note: prisma/platform.lock not found; the raw-SQL indexes were not merged (run platform db sync first)');
  }

  for (const f of fragments) messages.push(`fragment  ${f.action.padEnd(9)} prisma/fragments/${f.path.slice(fragmentsTarget.length + 1)}`);
  for (const path of staleFragments) messages.push(`fragment  remove    prisma/fragments/${path.slice(fragmentsTarget.length + 1)}`);
  for (const install of installs) messages.push(`migration ${install.action === 'copy' ? 'install' : 'adopt  '}  kvox:${install.id} -> ${install.installedDir}`);
  if (installs.length === 0) messages.push('migration up to date; nothing to install');
  if (platformLock) {
    messages.push(`platform.lock  ${platformLock.addedIndexes.length} raw-SQL index(es) added, ${platformLock.addedDirs.length} appMigrations entr${platformLock.addedDirs.length === 1 ? 'y' : 'ies'} added`);
  }
  messages.push(`kvox.lock  ${kvoxLockChanged ? 'write' : 'unchanged'}  (${names} names)`);

  return {
    root,
    prismaDir,
    names,
    dryRun: opts.dryRun === true,
    fragments,
    staleFragments,
    installs,
    kvoxLock: nextLock,
    kvoxLockText,
    kvoxLockChanged,
    ...(platformLock ? { platformLock } : {}),
    messages,
  };
}

function writeText(file: string, contents: string | Buffer): void {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, contents);
}

/**
 * Writes a plan: the fragment copies, the stale-copy removals, the migration
 * directories, `kvox.lock` and `platform.lock`. A migration directory that
 * already exists is never overwritten. Does nothing when the plan is a dry run.
 *
 * @param plan - From {@link planKvoxSync}.
 * @throws KvoxSyncError when a directory the plan would create has appeared meanwhile.
 * @stability experimental
 */
export function applyKvoxSync(plan: KvoxSyncPlan): void {
  if (plan.dryRun) return;
  const hostMigrations = join(plan.prismaDir, 'migrations');
  for (const install of plan.installs) {
    if (install.action !== 'copy') continue;
    const target = join(hostMigrations, install.installedDir, 'migration.sql');
    if (existsSync(target) || (existsSync(dirname(target)) && statSync(dirname(target)).isDirectory())) {
      throw new KvoxSyncError(`prisma/migrations/${install.installedDir} already exists; refusing to overwrite an installed migration`);
    }
    writeText(target, readFileSync(install.sourceFile));
  }
  for (const fragment of plan.fragments) {
    if (fragment.action !== 'unchanged') writeText(fragment.path, fragment.contents);
  }
  for (const stale of plan.staleFragments) rmSync(stale);
  if (plan.kvoxLockChanged) writeText(join(plan.prismaDir, KVOX_LOCK_FILE), plan.kvoxLockText);
  if (plan.platformLock?.changed) writeText(plan.platformLock.path, plan.platformLock.text);
}
