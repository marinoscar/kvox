import { existsSync, readFileSync, readdirSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';

import {
  KvoxLockError,
  KvoxSyncError,
  afterHostNames,
  applyKvoxSync,
  checkKvoxInstall,
  findMissingHostModels,
  planKvoxSync,
  readInventories,
  readManifest,
  sha256Hex,
  type KvoxSyncOptions,
} from '../src/index.js';
import { PACKAGE_DIR, cleanup, freshHost } from './helpers.js';

afterEach(cleanup);

const manifest = readManifest(join(PACKAGE_DIR, 'migrations'));
const ids = manifest.migrations.map((entry) => entry.id);

function sync(root: string, options: Partial<KvoxSyncOptions> = {}) {
  const plan = planKvoxSync({ root, platformSchemaDir: null, ...options });
  applyKvoxSync(plan);
  return plan;
}

const migrationDirs = (root: string) => readdirSync(join(root, 'prisma', 'migrations')).sort();

describe('afterHostNames', () => {
  it('numbers one second after the newest directory, one second apart', () => {
    expect(afterHostNames(['20260914130000_add_a', '20260914140000_add_b'], ['20270102000000_x', '20260101000000_y'])).toEqual([
      '20270102000001_kvox_add_a',
      '20270102000002_kvox_add_b',
    ]);
  });

  it('rolls over a minute, hour and day', () => {
    expect(afterHostNames(['20260914130000_a', '20260914130000_b'], ['20271231235959_x'])).toEqual(['20280101000000_kvox_a', '20280101000001_kvox_b']);
  });
});

describe('sync into a host with no kvox history (after-host)', () => {
  it('installs after the host migrations, writes the lock and merges platform.lock', () => {
    const root = freshHost();
    const plan = sync(root);
    expect(plan.names).toBe('after-host');

    const dirs = migrationDirs(root);
    expect(dirs).toHaveLength(2 + ids.length);
    const installed = dirs.slice(2);
    expect(installed.every((dir) => dir > '20270102000000_host_more')).toBe(true);
    expect(installed.map((dir) => dir.replace(/^\d{14}_kvox_/, ''))).toEqual(ids.map((id) => id.slice(15)));
    expect([...installed].sort()).toEqual(installed);

    const lock = JSON.parse(readFileSync(join(root, 'prisma', 'kvox.lock'), 'utf8'));
    expect(lock.lockVersion).toBe(1);
    expect(lock.migrations.map((m: { originId: string }) => m.originId)).toEqual(ids.map((id) => `kvox:${id}`));
    for (const [i, entry] of lock.migrations.entries()) {
      const bytes = readFileSync(join(root, 'prisma', 'migrations', entry.installedDir, 'migration.sql'));
      expect(sha256Hex(bytes)).toBe(manifest.migrations[i]!.sha256);
    }

    const platform = JSON.parse(readFileSync(join(root, 'prisma', 'platform.lock'), 'utf8'));
    expect(platform.rawSqlIndexes.map((i: { name: string }) => i.name)).toContain('host_only_idx');
    expect(platform.rawSqlIndexes).toHaveLength(1 + readInventories(PACKAGE_DIR).rawSqlIndexes.length);
    expect(platform.appMigrations).toEqual(expect.arrayContaining(installed));
    expect([...platform.appMigrations].sort()).toEqual(platform.appMigrations);

    const fragments = readdirSync(join(root, 'prisma', 'fragments')).filter((name) => name.startsWith('kvox.'));
    expect(fragments).toEqual(['kvox.ask.prisma', 'kvox.graph.prisma', 'kvox.notes.prisma', 'kvox.search.prisma', 'kvox.transcripts.prisma']);
    const head = readFileSync(join(root, 'prisma', 'fragments', 'kvox.ask.prisma'), 'utf8').split('\n');
    expect(head[0]).toBe('// GENERATED by kvox-db sync — do not edit');
    expect(head[1]).toBe('// source: @marinoscar/kvox-db:schema/kvox.ask.prisma');
  });

  it('is a no-op the second time, and a later run keeps the same names', async () => {
    const root = freshHost();
    sync(root);
    const before = migrationDirs(root);
    const lockText = readFileSync(join(root, 'prisma', 'kvox.lock'), 'utf8');
    const plan = sync(root);
    expect(plan.installs).toEqual([]);
    expect(plan.kvoxLockChanged).toBe(false);
    expect(plan.platformLock?.changed).toBe(false);
    expect(plan.fragments.every((f) => f.action === 'unchanged')).toBe(true);
    expect(migrationDirs(root)).toEqual(before);
    expect(readFileSync(join(root, 'prisma', 'kvox.lock'), 'utf8')).toBe(lockText);
    expect((await checkKvoxInstall({ root })).problems).toEqual([]);
  });

  it('check passes after a sync and fails on a one-byte change of either copy', async () => {
    const root = freshHost();
    sync(root);
    expect((await checkKvoxInstall({ root })).ok).toBe(true);

    const lock = JSON.parse(readFileSync(join(root, 'prisma', 'kvox.lock'), 'utf8'));
    const file = join(root, 'prisma', 'migrations', lock.migrations[3].installedDir, 'migration.sql');
    const original = readFileSync(file);
    // A comment-only change still counts: the hash covers every byte.
    writeFileSync(file, Buffer.concat([original, Buffer.from('\n')]));
    const changed = await checkKvoxInstall({ root });
    expect(changed.problems.map((p) => p.code)).toEqual(['INSTALLED_MODIFIED']);
    writeFileSync(file, original);
    expect((await checkKvoxInstall({ root })).ok).toBe(true);

    const fragment = join(root, 'prisma', 'fragments', 'kvox.graph.prisma');
    const text = readFileSync(fragment, 'utf8');
    writeFileSync(fragment, `${text} `);
    expect((await checkKvoxInstall({ root })).problems.map((p) => p.code)).toEqual(['FRAGMENT_MODIFIED']);
    writeFileSync(fragment, text);

    rmSync(join(root, 'prisma', 'migrations', lock.migrations[0].installedDir), { recursive: true });
    expect((await checkKvoxInstall({ root })).problems.map((p) => p.code)).toEqual(['LOCK_ENTRY_MISSING']);
  });

  it('check reports a missing lock, a stale fragment and a platform.lock without the indexes', async () => {
    const root = freshHost();
    sync(root);
    rmSync(join(root, 'prisma', 'kvox.lock'));
    writeFileSync(join(root, 'prisma', 'fragments', 'kvox.gone.prisma'), '// stale\n');
    writeFileSync(join(root, 'prisma', 'platform.lock'), readFileSync(join(root, 'prisma', 'platform.lock'), 'utf8').replace(/"rawSqlIndexes": \[[\s\S]*?\n  \]/, '"rawSqlIndexes": []'));
    const codes = (await checkKvoxInstall({ root })).problems.map((p) => p.code);
    expect(codes).toContain('LOCK_MISSING');
    expect(codes).toContain('FRAGMENT_STALE');
    expect(codes).toContain('PLATFORM_LOCK_INDEX_MISSING');
  });

  it('removes a stale generated fragment on sync', () => {
    const root = freshHost();
    sync(root);
    const stale = join(root, 'prisma', 'fragments', 'kvox.gone.prisma');
    writeFileSync(stale, '// stale\n');
    sync(root);
    expect(existsSync(stale)).toBe(false);
  });

  it('writes nothing on a dry run', () => {
    const root = freshHost();
    const plan = sync(root, { dryRun: true });
    expect(plan.installs).toHaveLength(ids.length);
    expect(migrationDirs(root)).toHaveLength(2);
    expect(existsSync(join(root, 'prisma', 'kvox.lock'))).toBe(false);
    expect(readdirSync(join(root, 'prisma', 'fragments'))).toEqual(['.gitkeep']);
  });
});

describe('sync with original names', () => {
  it('keeps the package directory names and warns that they sort before the host history', () => {
    const root = freshHost();
    const plan = sync(root, { names: 'original' });
    expect(migrationDirs(root).slice(0, ids.length)).toEqual(ids);
    expect(plan.messages.some((line) => line.startsWith('note:') && line.includes('--names after-host'))).toBe(true);
  });

  it('adopts directories that already exist byte-identical (the web app case) and chooses original names for the rest', () => {
    const root = freshHost();
    for (const id of ids.slice(0, 5)) {
      const dir = join(root, 'prisma', 'migrations', id);
      mkdirSync(dir, { recursive: true });
      writeFileSync(join(dir, 'migration.sql'), readFileSync(join(PACKAGE_DIR, 'migrations', id, 'migration.sql')));
    }
    const plan = planKvoxSync({ root, platformSchemaDir: null });
    expect(plan.names).toBe('original');
    expect(plan.installs.filter((i) => i.action === 'adopt')).toHaveLength(5);
    applyKvoxSync(plan);
    expect(ids.every((id) => migrationDirs(root).includes(id))).toBe(true);
  });

  it('refuses a directory that exists under an original name with other bytes', () => {
    const root = freshHost();
    const dir = join(root, 'prisma', 'migrations', ids[0]!);
    mkdirSync(dir, { recursive: true });
    writeFileSync(dir + '/migration.sql', '-- not the package copy\n');
    expect(() => planKvoxSync({ root, platformSchemaDir: null })).toThrow(KvoxSyncError);
  });

  it('keeps the policy the lock was written with', () => {
    const root = freshHost();
    sync(root);
    const lock = JSON.parse(readFileSync(join(root, 'prisma', 'kvox.lock'), 'utf8'));
    expect(planKvoxSync({ root, platformSchemaDir: null }).names).toBe('after-host');
    expect(lock.migrations[0].installedDir).toMatch(/_kvox_/);
  });
});

describe('sync refusals', () => {
  it('names the missing host model', () => {
    const root = freshHost();
    const schema = join(root, 'prisma', 'schema', 'platform.host.prisma');
    writeFileSync(schema, readFileSync(schema, 'utf8').replace(/model Job \{[\s\S]*?\n\}\n/, ''));
    expect(findMissingHostModels(join(root, 'prisma'), null)).toEqual(['Job']);
    expect(() => planKvoxSync({ root, platformSchemaDir: null })).toThrow(/model Job/);
  });

  it('refuses a platform.lock index listed with another definition', () => {
    const root = freshHost();
    const name = readInventories(PACKAGE_DIR).rawSqlIndexes[0]!.name;
    const file = join(root, 'prisma', 'platform.lock');
    const lock = JSON.parse(readFileSync(file, 'utf8'));
    lock.rawSqlIndexes.push({ name, definition: 'CREATE INDEX other ON public.t USING btree (a)' });
    writeFileSync(file, JSON.stringify(lock, null, 2));
    expect(() => planKvoxSync({ root, platformSchemaDir: null })).toThrow(KvoxLockError);
    expect(existsSync(join(root, 'prisma', 'kvox.lock'))).toBe(false);
  });

  it('refuses a package whose migration differs from the manifest', () => {
    const root = freshHost();
    const pkg = join(root, 'pkg');
    mkdirSync(join(pkg, 'migrations', ids[0]!), { recursive: true });
    const sourceManifest = readManifest(join(PACKAGE_DIR, 'migrations'));
    writeFileSync(join(pkg, 'migrations', 'manifest.json'), JSON.stringify({ manifestVersion: 1, migrations: [sourceManifest.migrations[0]] }));
    writeFileSync(join(pkg, 'migrations', ids[0]!, 'migration.sql'), '-- edited\n');
    expect(() => planKvoxSync({ root, platformSchemaDir: null, migrationsDir: join(pkg, 'migrations') })).toThrow(/sha256 mismatch/);
  });

  it('refuses to re-install a migration the lock says is installed but the folder lost', () => {
    const root = freshHost();
    sync(root);
    const lock = JSON.parse(readFileSync(join(root, 'prisma', 'kvox.lock'), 'utf8'));
    rmSync(join(root, 'prisma', 'migrations', lock.migrations[2].installedDir), { recursive: true });
    expect(() => planKvoxSync({ root, platformSchemaDir: null })).toThrow(/does not exist/);
  });
});
