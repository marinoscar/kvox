import { randomUUID } from 'node:crypto';

import { Prisma } from '../../core/index.js';
import type { KvoxPrismaClientLike } from '../../ports/index.js';
import { SEARCH_EMBEDDING_DIMENSIONS } from '../search.options.js';

// =============================================================================
// Fixtures of the search slice (issue #494, epic #491)
// =============================================================================
//
// `seedSearchCorpus` writes the smallest corpus a real-database spec needs to
// prove ranking, snippets and visibility: two transcripts and two notes owned by
// one user, each carrying a DISTINCT NONSENSE TERM (`zarquon`, `vorpal`,
// `grimwald`, `fnord`), plus a second user who owns nothing and must therefore
// find nothing.
//
// The distinct terms are not whimsy: one fixture set answers several independent
// questions without any test seeing another test's rows, and an accidental
// cross-match is impossible rather than merely unlikely.
//
// RAW SQL, NOT A GENERATED CLIENT. The rows belong to the transcripts and notes
// slices, whose code this slice must not import; the statements name only the
// columns the migrations require. The `tsvector` columns search reads are
// generated by the database, so there is nothing to compute here.
// =============================================================================

/**
 * The client the seed needs: raw statements only, so a spec can pass the test
 * host's generated client, a transaction or a double.
 *
 * @stability experimental
 */
export type SearchSeedClient = Pick<KvoxPrismaClientLike, '$queryRaw' | '$executeRaw'>;

/**
 * The words the seeded corpus is built around.
 *
 * @stability experimental
 */
export const SEARCH_CORPUS_TERMS = {
  /** In the first transcript's SEGMENT text only (its title never says it). */
  transcriptSegment: 'zarquon',
  /** In the second transcript's TITLE only. */
  transcriptTitle: 'vorpal',
  /** In the first note's BODY only. */
  noteBody: 'grimwald',
  /** In the second note's TITLE only. */
  noteTitle: 'fnord',
} as const;

/**
 * One seeded document.
 *
 * @stability experimental
 */
export interface SeededSearchDocument {
  /** The row id. */
  id: string;
  /** The document title. */
  title: string;
}

/**
 * What {@link seedSearchCorpus} wrote.
 *
 * @stability experimental
 */
export interface SeededSearchCorpus {
  /** The user who owns every document. */
  ownerId: string;
  /** A user who owns nothing and may see nothing. */
  strangerId: string;
  /** Two transcripts, in the order described by {@link SEARCH_CORPUS_TERMS}. */
  transcripts: [SeededSearchDocument, SeededSearchDocument];
  /** Two notes, in the order described by {@link SEARCH_CORPUS_TERMS}. */
  notes: [SeededSearchDocument, SeededSearchDocument];
}

/**
 * A vector of the stored width that is zero except on the given axes. Two such
 * vectors on distinct axes have cosine similarity 0 and a vector against itself
 * has 1, so a spec's expected ranking is a number written down rather than a
 * property of a model.
 *
 * @param axes - the non-zero components by index.
 * @returns the full-width vector.
 * @stability experimental
 */
export function sparseVector(axes: Record<number, number>): number[] {
  const values: number[] = new Array(SEARCH_EMBEDDING_DIMENSIONS).fill(0);

  for (const [index, value] of Object.entries(axes)) values[Number(index)] = value;

  return values;
}

/**
 * Writes the corpus described by {@link SEARCH_CORPUS_TERMS} for a fresh owner.
 *
 * Needs the platform schema and the domain migrations (the test host has both)
 * and a default organization. Safe to call more than once: every row gets fresh
 * ids and a fresh email.
 *
 * @param db - a client able to run raw statements on the database.
 * @returns the ids of what was written.
 * @stability experimental
 */
export async function seedSearchCorpus(db: SearchSeedClient): Promise<SeededSearchCorpus> {
  const ownerId = randomUUID();
  const strangerId = randomUUID();

  for (const [id, label] of [
    [ownerId, 'owner'],
    [strangerId, 'stranger'],
  ] as const) {
    await db.$executeRaw(Prisma.sql`
      INSERT INTO users (id, email, updated_at)
      VALUES (${id}::uuid, ${`search-corpus-${label}-${id}@example.test`}, now())
    `);
  }

  const transcripts: SeededSearchDocument[] = [];

  for (const spec of [
    {
      title: 'Quarterly pricing review',
      segments: [
        'We reviewed the packaging tiers before lunch.',
        `The only open item is the ${SEARCH_CORPUS_TERMS.transcriptSegment} migration, which slips a week.`,
      ],
    },
    {
      title: `The ${SEARCH_CORPUS_TERMS.transcriptTitle} planning call`,
      segments: ['Nothing on the agenda was contentious today.'],
    },
  ]) {
    transcripts.push(await insertTranscript(db, ownerId, spec.title, spec.segments));
  }

  const notes: SeededSearchDocument[] = [];

  for (const spec of [
    {
      title: 'Hiring plan',
      body: `Two roles open this quarter. The ${SEARCH_CORPUS_TERMS.noteBody} candidate interviews on Tuesday.`,
    },
    {
      title: `Offsite logistics ${SEARCH_CORPUS_TERMS.noteTitle}`,
      body: 'Venue booked; catering still to confirm.',
    },
  ]) {
    const id = randomUUID();

    await db.$executeRaw(Prisma.sql`
      INSERT INTO notes (id, owner_id, title, body, source_type, status, current_version, updated_at)
      VALUES (
        ${id}::uuid, ${ownerId}::uuid, ${spec.title}, ${spec.body},
        'document'::"NoteSourceType", 'ready'::"NoteStatus", 1, now()
      )
    `);
    notes.push({ id, title: spec.title });
  }

  return {
    ownerId,
    strangerId,
    transcripts: transcripts as [SeededSearchDocument, SeededSearchDocument],
    notes: notes as [SeededSearchDocument, SeededSearchDocument],
  };
}

/** One transcript with a single speaker and its segments, written live. */
async function insertTranscript(
  db: SearchSeedClient,
  ownerId: string,
  title: string,
  segments: readonly string[],
): Promise<SeededSearchDocument> {
  const transcriptId = randomUUID();
  const objectId = randomUUID();
  const speakerId = randomUUID();

  // The recording the transcript points at: an object in the default organization.
  await db.$executeRaw(Prisma.sql`
    INSERT INTO storage_objects (id, name, size, mime_type, storage_key, updated_at, org_id)
    SELECT
      ${objectId}::uuid, 'recording.m4a', 1024, 'audio/mp4', ${`search-corpus/${objectId}`}, now(),
      (SELECT id FROM organizations WHERE is_default LIMIT 1)
  `);

  await db.$executeRaw(Prisma.sql`
    INSERT INTO transcripts (id, owner_id, title, source_object_id, provider, status, current_version, updated_at)
    VALUES (
      ${transcriptId}::uuid, ${ownerId}::uuid, ${title}, ${objectId}::uuid, 'fake',
      'ready'::"TranscriptStatus", 1, now()
    )
  `);

  await db.$executeRaw(Prisma.sql`
    INSERT INTO transcript_speakers (id, transcript_id, label, display_name, color_index)
    VALUES (${speakerId}::uuid, ${transcriptId}::uuid, 'A', 'Speaker A', 0)
  `);

  for (const [position, text] of segments.entries()) {
    await db.$executeRaw(Prisma.sql`
      INSERT INTO transcript_segments (id, transcript_id, speaker_id, start_ms, end_ms, ordinal, text, words)
      VALUES (
        ${randomUUID()}::uuid, ${transcriptId}::uuid, ${speakerId}::uuid,
        ${position * 4000}, ${position * 4000 + 3500}, ${position}, ${text}, '[]'::jsonb
      )
    `);
  }

  return { id: transcriptId, title };
}
