#!/usr/bin/env node
// =============================================================================
// Write src/brand/identity.generated.ts from packages/shared/identity.json
// =============================================================================
//
// `packages/shared/identity.json` is the rebrand codemod's contract
// (`scripts/rename.mjs` rewrites it). The brand subpath of this package is
// published and cannot import the private `@app/shared` workspace, and JSON
// outside `rootDir` cannot be part of its build, so the four values it needs are
// copied into a committed TypeScript file by this script:
//
//   npm run brand:sync -w @marinoscar/kvox-web     write the file
//   npm run brand:check -w @marinoscar/kvox-web    exit 1 when it is stale (CI)
//
// `scripts/rename.mjs` runs the write after it changes the manifest, so a
// rebrand cannot leave the theme on the old colour. The check fails CI when
// someone edits `identity.json` by hand and forgets the write.
//
// Usage: node scripts/sync-brand-identity.mjs [--check]
// Exit: 0 in step (or written), 1 stale under --check, 2 unreadable manifest.
// Node built-ins only. Importing this module runs nothing.
// =============================================================================

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const PACKAGE_DIR = resolve(HERE, '..');
export const MANIFEST = resolve(PACKAGE_DIR, '..', 'shared', 'identity.json');
export const OUTPUT = join(PACKAGE_DIR, 'src', 'brand', 'identity.generated.ts');

/** The manifest fields the brand needs, in the order they are written. */
export const FIELDS = Object.freeze(['productName', 'tagline', 'themeColor', 'backgroundColor']);

/** The exact text of the generated file for a parsed manifest. */
export function render(identity) {
  for (const field of FIELDS) {
    if (typeof identity[field] !== 'string' || identity[field].trim() === '') {
      throw new Error(`\`${field}\` is missing (or is not a string) in ${MANIFEST}`);
    }
  }
  const lines = FIELDS.map((field) => `  ${field}: ${JSON.stringify(identity[field])},`);
  return [
    '// GENERATED by scripts/sync-brand-identity.mjs from packages/shared/identity.json.',
    '// Never edit by hand: `npm run brand:sync -w @marinoscar/kvox-web` rewrites it,',
    '// `scripts/rename.mjs` runs that on a rebrand and `npm run brand:check` fails on drift.',
    '',
    "import type { KvoxBrand } from './identity.js';",
    '',
    '/**',
    ' * The identity values of `packages/shared/identity.json` that the brand paints.',
    ' *',
    ' * @stability experimental',
    ' */',
    'export const KVOX_BRAND: KvoxBrand = {',
    ...lines,
    '};',
    '',
  ].join('\n');
}

/**
 * Writes (or checks) the generated file.
 *
 * @returns {{ ok: boolean, wrote: boolean }}
 */
export function syncBrandIdentity({ check = false } = {}) {
  if (!existsSync(MANIFEST)) throw new Error(`brand manifest not found at ${MANIFEST}`);
  const expected = render(JSON.parse(readFileSync(MANIFEST, 'utf8')));
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : null;
  if (current === expected) return { ok: true, wrote: false };
  if (check) return { ok: false, wrote: false };
  writeFileSync(OUTPUT, expected);
  return { ok: true, wrote: true };
}

const isDirectExecution =
  process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isDirectExecution) {
  const check = process.argv.includes('--check');
  try {
    const { ok, wrote } = syncBrandIdentity({ check });
    if (!ok) {
      console.error(
        'sync-brand-identity: packages/kvox-web/src/brand/identity.generated.ts is stale.\n' +
          '  Run: npm run brand:sync -w @marinoscar/kvox-web',
      );
      process.exit(1);
    }
    console.log(wrote ? 'sync-brand-identity: wrote identity.generated.ts' : 'sync-brand-identity: in step');
  } catch (err) {
    console.error(`sync-brand-identity: ${err.message}`);
    process.exit(2);
  }
}
